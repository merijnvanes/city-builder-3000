export function drawCollegeCampus(d, t) {
  campus(d, '#80a47a');
  d.flat(0.3, 0.35, 0.4, 0.38, 0.5, '#e0d3b4');
  d.flat(0.36, 0.4, 0.28, 0.25, 0.6, '#6d9d70');
  d.parts([
    ...[0.06, 0.73].map(x => [x + 0.105, 0.4, () => {
      hall(d, t, x, 0.12, 0.21, 0.55, 16, '#bd806a');
      d.roof(x - 0.01, 0.1, 0.23, 0.59, 17.5, 7, '#416f76');
    }]),
    [0.5, 0.2, () => {
      hall(d, t, 0.3, 0.07, 0.4, 0.22, 22, '#d5b88b');
      d.roof(0.28, 0.05, 0.44, 0.26, 23.5, 7, '#416f76');
      d.box(0.43, 0.1, 0.14, 0.16, 13.5, '#e4cfaa', 23.5);
      clockFaces(d, 0.43, 0.1, 0.14, 0.16, 28);
      d.box(0.42, 0.09, 0.16, 0.18, 1.5, C.trim, 37);
      d.hip(0.41, 0.08, 0.18, 0.2, 38.5, 9, '#3f7e7b');
      d.line(0.5, 0.18, 47.5, 0.5, 0.18, 52, C.gold, 1);
    }],
    [0.5, 0.78, () => {
      // Low ceremonial gate frames the quad rather than hiding it.
      for (const x of [0.3, 0.64]) {
        d.box(x, 0.75, 0.06, 0.08, 10, '#d5b88b');
        d.hip(x - 0.01, 0.74, 0.08, 0.1, 10, 3, '#416f76');
      }
      d.line(0.36, 0.79, 8, 0.64, 0.79, 8, C.gold, 1.3);
      steps(d, 0.38, 0.79, 0.24, 2);
    }],
    [0.14, 0.85, () => d.tree(0.14, 0.85, 1)],
    [0.85, 0.85, () => d.tree(0.85, 0.85, 1)],
    [0.6, 0.53, () => flag(d, 0.6, 0.53, 14, '#8b5e99')],
  ]);
}

